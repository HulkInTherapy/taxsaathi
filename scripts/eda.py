"""
Exploratory data analysis (EDA) of the knowledge base and the gold question set.

Produces charts in docs/figures/ and a short report docs/eda.md with the numbers:
chunks per law and per source, chunk length distribution, most frequent legal terms,
how many chunks are in force at each point in time (by law), and the gold set's category /
language mix. Run after ingest:  python -m scripts.eda
"""
from __future__ import annotations

import json
from collections import Counter
from datetime import date, timedelta

import matplotlib

matplotlib.use("Agg")  # no display on the server
import matplotlib.pyplot as plt  # noqa: E402

from src import config  # noqa: E402
from src.ingest.ingest import read_chunks  # noqa: E402
from src.retrieval.bm25 import tokenize  # noqa: E402
from src.retrieval.date_filter import chunk_range  # noqa: E402

FIG_DIR = config.ROOT / "docs" / "figures"
REPORT = config.ROOT / "docs" / "eda.md"

# Categorical palette in fixed order (validated reference palette); text stays in ink colours.
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
LAW_ORDER = ["new_act", "old_act", "gst", "mapping", "general"]
SHORT_LAW = {"new_act": "IT Act 2025", "old_act": "IT Act 1961", "gst": "GST", "mapping": "Section mapping", "general": "General"}

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "axes.edgecolor": GRID,
    "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2, "text.color": INK,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8, "axes.axisbelow": True,
    "axes.spines.top": False, "axes.spines.right": False, "font.size": 10,
    "axes.titlesize": 12, "axes.titleweight": "bold", "axes.titlelocation": "left",
})


def _save(fig, name: str) -> str:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(FIG_DIR / name, dpi=150)
    plt.close(fig)
    return f"figures/{name}"


def _hbar(counter: Counter, title: str, name: str, xlabel: str = "chunks", top: int | None = None) -> str:
    items = counter.most_common(top)[::-1]
    fig, ax = plt.subplots(figsize=(7, max(2.2, 0.32 * len(items) + 1)))
    labels = [str(k) for k, _ in items]
    vals = [v for _, v in items]
    ax.barh(labels, vals, color=SERIES[0], height=0.65)
    for y, v in enumerate(vals):  # direct labels in ink, not series colour
        ax.text(v, y, f" {v}", va="center", color=INK2, fontsize=9)
    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.grid(axis="y", visible=False)
    return _save(fig, name)


def load_gold() -> list[dict]:
    path = config.EVAL_DIR / "gold.jsonl"
    files = [path] if path.exists() else sorted(config.EVAL_DIR.glob("gold_*.jsonl"))
    rows = []
    for f in files:
        rows += [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
    return rows


def in_force_timeline(chunks: list[dict]) -> str:
    """Line chart: number of chunks in force on the 1st of each month, by law."""
    start, end = date(2017, 1, 1), date(2027, 3, 1)
    months = []
    d = start
    while d <= end:
        months.append(d)
        d = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
    fig, ax = plt.subplots(figsize=(8, 3.6))
    laws = [l for l in LAW_ORDER if any(c["law"] == l for c in chunks)]
    for i, law in enumerate(laws):
        sub = [chunk_range(c) for c in chunks if c["law"] == law and (c["effective_from"] or c["effective_to"])]
        ys = [sum(1 for f, t in sub if f <= m <= t) for m in months]
        ax.plot(months, ys, color=SERIES[i % len(SERIES)], linewidth=2, label=SHORT_LAW.get(law, law))
    top = ax.get_ylim()[1]
    for x, lab, ha in [(date(2025, 9, 22), "GST 2.0 ", "right"), (date(2026, 4, 1), " 2025 Act", "left")]:
        ax.axvline(x, color=INK2, linewidth=0.8, linestyle="--")
        ax.text(x, top * 0.78, lab, color=INK2, fontsize=8, va="top", ha=ha)
    ax.set_title("Dated chunks in force over time, by law")
    ax.set_ylabel("chunks in force")
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    return _save(fig, "effective_date_coverage.png")


def main() -> None:
    chunks = read_chunks()
    gold = load_gold()
    lines = ["# EDA — knowledge base and gold set", "",
             f"Generated by `python -m scripts.eda` (today = {config.TODAY}).", ""]

    # ---- knowledge base
    lens = sorted(c["n_tokens"] for c in chunks)
    by_law = Counter(c["law"] for c in chunks)
    by_doc = Counter(c["doc_id"] for c in chunks)
    by_topic = Counter(c["topic"] or "(none)" for c in chunks)
    verified = Counter(c["verified"] or "(blank)" for c in chunks)
    dated = sum(1 for c in chunks if c["effective_from"] or c["effective_to"])
    f_law = _hbar(by_law, "Chunks per law", "chunks_per_law.png")
    f_doc = _hbar(by_doc, "Chunks per source document (top 25)", "chunks_per_source.png", top=25)

    fig, ax = plt.subplots(figsize=(7, 3.2))
    ax.hist(lens, bins=20, color=SERIES[0], edgecolor=SURFACE, linewidth=2)
    ax.axvspan(60, 220, color=SERIES[2], alpha=0.08, label="target 60–220 words")
    ax.set_title("Chunk length (words)")
    ax.set_xlabel("words per chunk")
    ax.set_ylabel("chunks")
    ax.legend(frameon=False, fontsize=8)
    f_len = _save(fig, "chunk_length_hist.png")

    terms = Counter()
    for c in chunks:
        terms.update(t for t in tokenize(c["text"]) if len(t) >= 3 and not t.isdigit())
    f_terms = _hbar(Counter(dict(terms.most_common(25))), "Top 25 terms in the knowledge base", "top_terms.png", xlabel="occurrences")
    sections = Counter(c["section"] for c in chunks if c["section"])
    f_time = in_force_timeline(chunks)

    median = lens[len(lens) // 2] if lens else 0
    lines += ["## Knowledge base", "",
              f"- Chunks: **{len(chunks)}** from **{len(by_doc)}** source documents",
              f"- Words per chunk: min {lens[0] if lens else 0}, median {median}, mean {sum(lens) / max(1, len(lens)):.0f}, max {lens[-1] if lens else 0}",
              f"- Chunks with effective dates: {dated} ({100 * dated / max(1, len(chunks)):.0f}%)",
              f"- Verified: " + ", ".join(f"{k} = {v}" for k, v in verified.most_common()),
              "", "| law | chunks |", "|---|---|"] + [f"| {k} | {v} |" for k, v in by_law.most_common()] + [
              "", "| topic | chunks |", "|---|---|"] + [f"| {k} | {v} |" for k, v in by_topic.most_common()] + [
              "", f"Most-covered sections: " + ", ".join(f"{k} ({v})" for k, v in sections.most_common(15)), "",
              f"![chunks per law]({f_law})", f"![chunks per source]({f_doc})", f"![chunk length]({f_len})",
              f"![top terms]({f_terms})", f"![in force over time]({f_time})", ""]

    # ---- gold set
    if gold:
        cats = Counter(r.get("category", "?") for r in gold)
        langs = Counter(r.get("language", "?") for r in gold)
        diff = Counter(r.get("difficulty", "?") for r in gold)
        ans = sum(1 for r in gold if r.get("answerable", True))
        f_cat = _hbar(cats, "Gold questions per category", "gold_categories.png", xlabel="questions")
        kb_ids = {c["id"] for c in chunks}
        missing = sorted({g for r in gold for g in r.get("gold_chunk_ids", []) if g not in kb_ids})
        lines += ["## Gold set", "", f"- Questions: **{len(gold)}** (answerable {ans}, not answerable {len(gold) - ans})",
                  "- Language: " + ", ".join(f"{k} = {v}" for k, v in langs.most_common()),
                  "- Difficulty: " + ", ".join(f"{k} = {v}" for k, v in diff.most_common()),
                  "", "| category | questions |", "|---|---|"] + [f"| {k} | {v} |" for k, v in cats.most_common()] + [
                  "", f"- gold_chunk_ids not found in the KB: {len(missing)}" + (f" ({', '.join(missing[:20])})" if missing else ""),
                  "", f"![gold categories]({f_cat})", ""]
    else:
        lines += ["## Gold set", "", "No gold files found yet.", ""]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT} and figures in {FIG_DIR}")


if __name__ == "__main__":
    main()
